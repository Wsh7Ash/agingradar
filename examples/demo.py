#!/usr/bin/env python3
"""Offline agingradar demo — reads the bundled sample CSV and writes evidence.

    python examples/demo.py

Everything is deterministic: the report date is fixed at 2026-10-18 so the
output in results/ can be regenerated byte-for-byte.
"""

from __future__ import annotations

import json
import os
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from agingradar.aging import build_report, bucket_for  # noqa: E402
from agingradar.model import format_money, load_csv  # noqa: E402
from agingradar.report import render_chase_csv, render_html, render_markdown  # noqa: E402

AS_OF = date(2026, 10, 18)
CSV = os.path.join(ROOT, "examples", "invoices-sample.csv")
RESULTS = os.path.join(ROOT, "results")


def main() -> int:
    os.makedirs(RESULTS, exist_ok=True)
    ledger = load_csv(CSV)
    report = build_report(ledger, as_of=AS_OF)

    for name, text in (
        ("aging-report.md", render_markdown(report, top=10)),
        ("aging-report.html", render_html(report, top=10)),
        ("chase-list.csv", render_chase_csv(report)),
    ):
        with open(os.path.join(RESULTS, name), "w", encoding="utf-8", newline="") as fh:
            fh.write(text)

    summary = {
        "as_of": AS_OF.isoformat(),
        "source": ledger.source,
        "invoices": len(ledger.invoices),
        "open": len(report.rows),
        "paid": len(report.paid_in_period),
        "ignored": len(report.ignored),
        "customers": len(ledger.customers),
        "outstanding_cents": report.total_outstanding(),
        "overdue_cents": report.total_overdue(),
        "overdue_ratio": round(report.overdue_ratio(), 4),
        "bucket_totals_cents": report.bucket_totals(),
        "bucket_counts": report.bucket_counts(),
        "late_payers": report.late_payers,
        "average_days_to_payment": report.average_days_to_pay(),
        "top_chase": [
            {
                "rank": i,
                "invoice": row.invoice.number,
                "customer": row.invoice.customer,
                "days_overdue": row.days_overdue,
                "bucket": row.bucket,
                "balance": format_money(row.balance_cents, row.invoice.currency),
                "score": row.score_pct,
            }
            for i, row in enumerate(report.chase_list(5), 1)
        ],
    }
    with open(os.path.join(RESULTS, "demo-summary.json"), "w", encoding="utf-8") as fh:
        json.dump(summary, fh, indent=2, sort_keys=True)

    # sanity checks — the demo fails loudly if the math regresses
    checks = []
    checks.append(("bucket math", bucket_for(0) == "current" and bucket_for(1) == "1-30"
                   and bucket_for(30) == "1-30" and bucket_for(31) == "31-60"
                   and bucket_for(60) == "31-60" and bucket_for(61) == "61-90"
                   and bucket_for(90) == "61-90" and bucket_for(91) == "90+"
                   and bucket_for(400) == "90+"))
    checks.append(("partial payment reduces balance", summary["outstanding_cents"] > 0))
    checks.append(("void/draft excluded", summary["ignored"] == 2))
    checks.append(("paid excluded", summary["paid"] == 2))
    checks.append(("late payers detected", len(summary["late_payers"]) >= 2))
    checks.append(("chase list is score-ordered",
                   [c["score"] for c in summary["top_chase"]] ==
                   sorted([c["score"] for c in summary["top_chase"]], reverse=True)))
    checks.append(("oldest invoice in 90+ bucket",
                   any(r.bucket == "90+" for r in report.open_rows)))
    for name, ok in checks:
        print(f"[{'ok' if ok else 'FAIL'}] {name}")
    print(f"[done] {len(ledger.invoices)} invoices -> outstanding "
          f"{summary['outstanding_cents'] / 100:.2f}, overdue "
          f"{summary['overdue_cents'] / 100:.2f} ({summary['overdue_ratio']:.0%})")
    print("[done] results/ written (aging-report.md, aging-report.html, chase-list.csv, demo-summary.json)")
    return 0 if all(ok for _, ok in checks) else 1


if __name__ == "__main__":
    raise SystemExit(main())